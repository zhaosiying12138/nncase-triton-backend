    private static void AppendRuntimeHelpers(StringBuilder sb)
    {
        sb.AppendLine(
            """
            import ctypes
            import math
            import os
            import re
            import time

            _DL_TENSORS = []
            _TORCH = None
            _PE_STREAMS = []
            _KV_STATE = {"total_tokens": 0, "entry_depth": 0, "current_start": 0, "current_length": 0, "cache": {}}
            _TRITON_VERBOSE_COUNT = 0
            _TRITON_VERBOSE_LIMIT_REPORTED = False

            class _DLDevice(ctypes.Structure):
                _fields_ = [("device_type", ctypes.c_int), ("device_id", ctypes.c_int)]

            class _DLDataType(ctypes.Structure):
                _fields_ = [("code", ctypes.c_uint8), ("bits", ctypes.c_uint8), ("lanes", ctypes.c_uint16)]

            class _DLTensor(ctypes.Structure):
                _fields_ = [
                    ("data", ctypes.c_void_p),
                    ("device", _DLDevice),
                    ("ndim", ctypes.c_int32),
                    ("dtype", _DLDataType),
                    ("shape", ctypes.POINTER(ctypes.c_int64)),
                    ("strides", ctypes.POINTER(ctypes.c_int64)),
                    ("byte_offset", ctypes.c_uint64),
                ]

            class _DLManagedTensor(ctypes.Structure):
                pass

            _DLManagedTensor._fields_ = [
                ("dl_tensor", _DLTensor),
                ("manager_ctx", ctypes.c_void_p),
                ("deleter", ctypes.c_void_p),
            ]

            _PyCapsule_New = ctypes.pythonapi.PyCapsule_New
            _PyCapsule_New.restype = ctypes.py_object
            _PyCapsule_New.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_void_p]

            class _BufferRef:
                def __init__(self, desc):
                    self.desc = desc

            def _require_torch():
                global _TORCH
                if _TORCH is None:
                    import torch
                    _TORCH = torch
                    if torch.cuda.is_available():
                        torch.cuda.set_device(__nncase_triton_metadata__.get("device_id", 0))
                return _TORCH

            def _dtype_from_typecode(typecode):
                torch = _require_torch()
                return {
                    0: torch.bool,
                    2: torch.int8,
                    3: torch.int16,
                    4: torch.int32,
                    5: torch.int64,
                    6: torch.uint8,
                    10: torch.float16,
                    11: torch.float32,
                    12: torch.float64,
                    13: torch.bfloat16,
                }.get(int(typecode))

            def _dtype_from_name(name):
                torch = _require_torch()
                name = re.sub(r"<[^>]+>", "", str(name))
                return {
                    "DataTypes.Boolean": torch.bool,
                    "DataTypes.Int8": torch.int8,
                    "DataTypes.Int16": torch.int16,
                    "DataTypes.Int32": torch.int32,
                    "DataTypes.Int64": torch.int64,
                    "DataTypes.UInt8": torch.uint8,
                    "DataTypes.Float16": torch.float16,
                    "DataTypes.Float32": torch.float32,
                    "DataTypes.Float64": torch.float64,
                    "DataTypes.BFloat16": torch.bfloat16,
                }[name]

            def _vector_lanes_from_text(text):
                match = re.search(r"<([^>]+)>", str(text or ""))
                if not match:
                    return ()
                lanes = []
                for item in match.group(1).split(","):
                    item = item.strip()
                    if item:
                        lanes.append(int(item))
                return tuple(lanes)

            def _desc_vector_lanes(desc, type_text=None):
                lanes = _vector_lanes_from_text((desc or {}).get("dtype"))
                if lanes:
                    return lanes
                lanes = _vector_lanes_from_text((desc or {}).get("type"))
                if lanes:
                    return lanes
                return _vector_lanes_from_text(type_text)

            def _lane_strides(lanes):
                running = 1
                strides = []
                for lane in reversed(tuple(int(x) for x in lanes)):
                    strides.insert(0, running)
                    running *= max(1, lane)
                return tuple(strides)

            def _append_vector_lanes_to_shape(shape, lanes):
                return tuple(shape) + tuple(int(x) for x in lanes)

            def _append_vector_lanes_to_strides(strides, lanes):
                lanes = tuple(int(x) for x in lanes)
                if not lanes:
                    return tuple(strides)
                lane_elems = math.prod(lanes)
                return tuple(int(stride) * lane_elems for stride in strides) + _lane_strides(lanes)

            def _dlpack_dtype(dtype):
                torch = _require_torch()
                if dtype is torch.bool:
                    return _DLDataType(6, 8, 1)
                if dtype is torch.int8:
                    return _DLDataType(0, 8, 1)
                if dtype is torch.int16:
                    return _DLDataType(0, 16, 1)
                if dtype is torch.int32:
                    return _DLDataType(0, 32, 1)
                if dtype is torch.int64:
                    return _DLDataType(0, 64, 1)
                if dtype is torch.uint8:
                    return _DLDataType(1, 8, 1)
                if dtype is torch.float16:
                    return _DLDataType(2, 16, 1)
                if dtype is torch.float32:
                    return _DLDataType(2, 32, 1)
                if dtype is torch.float64:
                    return _DLDataType(2, 64, 1)
                if dtype is torch.bfloat16:
                    return _DLDataType(4, 16, 1)
                raise TypeError(f"unsupported dtype for dlpack bridge: {dtype}")

            def _tensor_from_pointer(ptr, dtype, shape, strides):
                torch = _require_torch()
                shape = tuple(int(x) for x in shape)
                strides = tuple(int(x) for x in strides)
                if math.prod(shape) == 0:
                    return torch.empty_strided(shape, strides, dtype=dtype, device="cuda")
                shape_arr = (ctypes.c_int64 * len(shape))(*shape)
                stride_arr = (ctypes.c_int64 * len(strides))(*strides)
                managed = _DLManagedTensor()
                managed.dl_tensor = _DLTensor(
                    ctypes.c_void_p(int(ptr)),
                    _DLDevice(2, __nncase_triton_metadata__.get("device_id", 0)),
                    len(shape),
                    _dlpack_dtype(dtype),
                    shape_arr,
                    stride_arr,
                    0,
                )
                managed.manager_ctx = None
                managed.deleter = None
                capsule = _PyCapsule_New(ctypes.addressof(managed), b"dltensor", None)
                _DL_TENSORS.append((managed, shape_arr, stride_arr))
                return torch.utils.dlpack.from_dlpack(capsule)

            def _tensor_from_arg(arg):
                if isinstance(arg, _BufferRef):
                    raise TypeError("buffer refs need a launch context")
                ptr, shape, strides, _, typecode = arg
                if int(typecode) >= 0xF0:
                    return {"__nncase_reference__": arg}
                dtype = _dtype_from_typecode(typecode)
                if dtype is None:
                    raise TypeError(f"unsupported nncase runtime typecode: {typecode}")
                return _tensor_from_pointer(ptr, dtype, shape, strides)

            def _parse_type_shape(type_text):
                match = re.search(r"\[(.*)\]", type_text or "")
                if not match:
                    return []
                body = match.group(1).strip()
                if not body:
                    return []
                return [part.strip() for part in body.split(",")]

            def _bound_shape(context, value):
                if isinstance(value, _BufferRef):
                    return _resolve_shape(context, value.desc)
                if isinstance(value, tuple) and len(value) >= 2:
                    return tuple(int(x) for x in value[1])
                if hasattr(value, "shape"):
                    return tuple(int(x) for x in value.shape)
                return ()

            def _symbol_env(context):
                env = dict(context.get("symbol_env", {}))
                context["symbol_env"] = env
                for parameter in context.get("function_metadata", {}).get("parameter_descriptors", []):
                    name = parameter.get("name")
                    if name not in context.get("bound_args", {}):
                        continue
                    if isinstance(context["bound_args"][name], _BufferRef):
                        continue
                    shape_tokens = _parse_type_shape(parameter.get("type", ""))
                    actual_shape = _bound_shape(context, context["bound_args"][name])
                    for token, actual in zip(shape_tokens, actual_shape):
                        if token and not token.lstrip("-").isdigit():
                            env.setdefault(token, int(actual))
                    context["symbol_env"] = env
                context["symbol_env"] = env
                return env

            def _eval_expression(expr, env):
                expr = str(expr).strip()
                ternary = re.fullmatch(r"\(?\s*([A-Za-z_][A-Za-z0-9_]*)\s*==\s*([0-9]+)\s*\?\s*([0-9]+)\s*:\s*([0-9]+)\s*\)?", expr)
                if ternary:
                    sym, cmp_value, true_value, false_value = ternary.groups()
                    return int(true_value) if int(env.get(sym, 0)) == int(cmp_value) else int(false_value)
                safe_expr = expr.replace("&&", " and ").replace("||", " or ")
                return int(eval(safe_expr, {"__builtins__": {}}, env))

            def _eval_dim(context, dim):
                env = _symbol_env(context)
                if dim.get("kind") == "fixed":
                    return int(dim.get("value", 0))
                if dim.get("symbol"):
                    return int(env[dim["symbol"]])
                if dim.get("expression"):
                    return _eval_expression(dim["expression"], env)
                raise ValueError(f"cannot resolve dynamic CUDA/Triton dimension: {dim}")

            def _resolve_shape(context, desc):
                return tuple(_eval_dim(context, dim) for dim in desc.get("shape", []))

            def _resolve_strides(context, desc, shape=None):
                strides = desc.get("strides", [])
                if strides:
                    return tuple(_eval_dim(context, dim) for dim in strides)
                shape = tuple(shape if shape is not None else _resolve_shape(context, desc))
                result = []
                running = 1
                for dim in reversed(shape):
                    result.insert(0, running)
                    running *= max(1, int(dim))
                return tuple(result)

            def _resolve_offset(context, memory):
                env = _symbol_env(context)
                base = memory.get("base_start")
                if base is None:
                    base_value = 0
                elif str(base).strip().lstrip("-").isdigit():
                    base_value = int(base)
                else:
                    base_value = _eval_expression(base, env)
                return base_value + _eval_dim(context, memory.get("span_start_bytes", {"kind": "fixed", "value": 0}))

            def _pool_pointer(context, location):
                if location == "Data":
                    return int(context["data_pool"])
                if location == "Output":
                    return int(context["output_pool"])
                if location == "Rdata":
                    return int(context["rdata_pool"])
                if location == "ThreadLocalRdata":
                    return int(context["rdata_pool"]) + int(context["module_metadata"].get("rdata_pool_size", 0))
                if location == "BlockLocalRdata":
                    return (
                        int(context["rdata_pool"])
                        + int(context["module_metadata"].get("rdata_pool_size", 0))
                        + int(context["module_metadata"].get("thread_local_rdata_pool_size", 0))
                    )
                if location == "BlockLocalData":
                    return int(context["data_pool"])
                raise ValueError(f"unsupported CUDA/Triton memory location: {location}")

            def _tensor_from_desc(context, desc):
                memory = desc["memory"]
                ptr = _pool_pointer(context, memory.get("location")) + _resolve_offset(context, memory)
                global_shape = _resolve_shape(context, desc)
                shape, _ = _local_shape_and_offsets(context, desc, global_shape)
                strides = _resolve_strides(context, desc, shape)
                lanes = _desc_vector_lanes(desc)
                shape = _append_vector_lanes_to_shape(shape, lanes)
                strides = _append_vector_lanes_to_strides(strides, lanes)
                return _tensor_from_pointer(ptr, _dtype_from_name(desc["dtype"]), shape, strides)

            def _find_launch_buffer_desc(context, name, launch_meta=None, index=None):
                if launch_meta:
                    buffer_arguments = launch_meta.get("buffer_arguments", {})
                    if index is not None:
                        direct = buffer_arguments.get(f"arg{index}")
                        if direct is not None:
                            return direct
                    for desc in buffer_arguments.values():
                        if desc.get("name") == name:
                            return desc
                return context.get("function_metadata", {}).get("buffers", {}).get(name)

            def _resolve_nested_argument(context, name, index, launch_meta):
                if name in context.get("bound_args", {}):
                    return context["bound_args"][name]
                desc = _find_launch_buffer_desc(context, name, launch_meta, index)
                if desc is not None:
                    return _BufferRef(desc)
                return name

            def _strip_l0(name):
                return name[:-3] if isinstance(name, str) and name.endswith("_L0") else name

            def _parameter_desc(context, name):
                for parameter in context.get("function_metadata", {}).get("parameter_descriptors", []):
                    if parameter.get("name") == name:
                        return parameter
                return None

            def _is_reference_parameter(context, name):
                parameter = _parameter_desc(context, name)
                return parameter is not None and str(parameter.get("type", "")).startswith("&")

            def _vector_lanes_for_name(context, name):
                desc = _find_launch_buffer_desc(context, name, context.get("current_launch_metadata"))
                lanes = _desc_vector_lanes(desc) if desc is not None else ()
                if lanes:
                    return lanes
                base = _strip_l0(name)
                arg = context.get("bound_args", {}).get(base)
                if isinstance(arg, _BufferRef):
                    lanes = _desc_vector_lanes(arg.desc)
                    if lanes:
                        return lanes
                parameter = _parameter_desc(context, base)
                return _vector_lanes_from_text((parameter or {}).get("type"))

            def _dtype_for_name(context, name, fallback=None):
                desc = _find_launch_buffer_desc(context, name, context.get("current_launch_metadata"))
                if desc is not None:
                    return _dtype_from_name(desc["dtype"])
                base = _strip_l0(name)
                if base in context.get("bound_args", {}) and not _is_reference_parameter(context, base):
                    return _get_tensor(context, base).dtype
                if fallback is not None:
                    return fallback.dtype
                return _require_torch().float32

            def _allocate_like_for_name(context, name, like=None):
                torch = _require_torch()
                desc = _find_launch_buffer_desc(context, name, context.get("current_launch_metadata"))
                if desc is not None and desc.get("memory", {}).get("location") not in ("Input",):
                    try:
                        return _tensor_from_desc(context, desc)
                    except Exception:
                        pass
                base = _strip_l0(name)
                if base in context.get("bound_args", {}) and not _is_reference_parameter(context, base):
                    base_tensor = _get_tensor(context, base)
                    return torch.empty_strided(tuple(base_tensor.shape), tuple(base_tensor.stride()), dtype=base_tensor.dtype, device=base_tensor.device)
                if like is None:
                    raise KeyError(f"cannot infer storage for CUDA/Triton temporary {name}")
                return torch.empty_strided(tuple(like.shape), tuple(like.stride()), dtype=like.dtype, device=like.device)

            def _literal_value(name):
                if name == "None":
                    return None
                if name == "True":
                    return True
                if name == "False":
                    return False
                try:
                    if isinstance(name, str) and re.fullmatch(r"[-+]?[0-9]+", name):
                        return int(name)
                    if isinstance(name, str) and re.fullmatch(r"[-+]?[0-9]*\.[0-9]+([eE][-+]?[0-9]+)?", name):
                        return float(name)
                except TypeError:
                    return name
                return name

            def _get_tensor(context, name, like=None):
                literal = _literal_value(name)
                if literal is not name:
                    return literal
                values = context.setdefault("values", {})
                if name in values:
                    return values[name]
                if name in context.get("bound_args", {}):
                    if _is_reference_parameter(context, name):
                        values[name] = {"__nncase_reference__": context["bound_args"][name]}
                    else:
                        arg = context["bound_args"][name]
                        values[name] = _tensor_from_desc(context, arg.desc) if isinstance(arg, _BufferRef) else _tensor_from_arg(arg)
                    return values[name]
                desc = _find_launch_buffer_desc(context, name, context.get("current_launch_metadata"))
                if desc is not None:
                    values[name] = _tensor_from_desc(context, desc)
                    return values[name]
                values[name] = _allocate_like_for_name(context, name, like)
                return values[name]

            def _write_tensor(context, name, value):
                torch = _require_torch()
                dest = _get_tensor(context, name, value)
                if isinstance(dest, dict):
                    raise TypeError(f"cannot write tensor result into reference argument {name}")
                if not hasattr(value, "shape"):
                    value = torch.as_tensor(value, dtype=dest.dtype, device=dest.device)
                if tuple(value.shape) != tuple(dest.shape):
                    value = value.reshape(tuple(dest.shape))
                if value.dtype != dest.dtype:
                    value = value.to(dest.dtype)
                dest.copy_(value)
                context.setdefault("values", {})[name] = dest
                return dest

            def _copy_tensor(context, dest_name, src_name):
                src = _get_tensor(context, src_name)
                if isinstance(src, dict):
                    context.setdefault("values", {})[dest_name] = src
                    return src
                return _write_tensor(context, dest_name, src)

            def _split_top_level_csv(text):
                result = []
                depth = 0
                start = 0
                for index, ch in enumerate(text or ""):
                    if ch == "(":
                        depth += 1
                    elif ch == ")":
                        depth = max(0, depth - 1)
                    elif ch == "," and depth == 0:
                        result.append(text[start:index].strip())
                        start = index + 1
                tail = (text or "")[start:].strip()
                if tail:
                    result.append(tail)
                return result

            def _distributed_axis_policies(type_text):
                match = re.search(r"\],\s*\((.*?)\),\s*\[", type_text or "")
                if not match:
                    return []
                return _split_top_level_csv(match.group(1))

            def _distributed_is_partial(type_text):
                return "Partial: True" in (type_text or "")

            def _distributed_shard_axes(type_text):
                axes = []
                for tensor_axis, policy in enumerate(_distributed_axis_policies(type_text)):
                    if re.fullmatch(r"S\(\s*\d+\s*\)", policy or ""):
                        axes.append(tensor_axis)
                return axes

            def _desc_distributed_type(desc):
                return (desc or {}).get("distributed_type") or ""

            def _local_shape_and_offsets(context, desc, shape=None, type_text=None):
                shape = tuple(int(x) for x in (shape if shape is not None else _resolve_shape(context, desc)))
                offsets = [0] * len(shape)
                local_shape = list(shape)
                type_text = type_text if type_text is not None else _desc_distributed_type(desc)
                pe_count = int(context.get("module_metadata", {}).get("pe_count", 1) or 1)
                pools = context.get("all_data_pools") or ()
                if pools:
                    pe_count = max(1, len(pools))
                pe_id = int(context.get("pe_id", 0))
                for axis in _distributed_shard_axes(type_text):
                    if axis >= len(shape):
                        continue
                    dim = int(shape[axis])
                    local_dim = (dim + pe_count - 1) // pe_count if pe_count else dim
                    offset = pe_id * local_dim
                    offsets[axis] = offset
                    local_shape[axis] = max(0, min(local_dim, dim - offset))
                return tuple(local_shape), tuple(offsets)

            def _slice_tuple(offsets, local_shape):
                return tuple(slice(int(offset), int(offset) + int(size)) for offset, size in zip(offsets, local_shape))

            def _slice_with_trailing_lanes(offsets, local_shape, trailing_rank):
                return _slice_tuple(offsets, local_shape) + tuple(slice(None) for _ in range(max(0, int(trailing_rank))))

            def _empty_like_global(desc, global_shape, device, type_text=None):
                torch = _require_torch()
                dtype = _dtype_from_name(desc["dtype"])
                lanes = _desc_vector_lanes(desc, type_text)
                return torch.empty(_append_vector_lanes_to_shape(global_shape, lanes), dtype=dtype, device=device)

            def _materialize_global_tensor(contexts, name, desc, type_text=None):
                torch = _require_torch()
                type_text = type_text if type_text is not None else _desc_distributed_type(desc)
                tensors = [_get_tensor(context, name) for context in contexts]
                tensors = [tensor for tensor in tensors if hasattr(tensor, "shape")]
                if not tensors:
                    raise TypeError(f"cannot materialize non-tensor CUDA/Triton value {name}")

                shard_axes = _distributed_shard_axes(type_text)
                if not shard_axes:
                    if _distributed_is_partial(type_text):
                        result = tensors[0].float()
                        for tensor in tensors[1:]:
                            result = result + tensor.float()
                        return result.to(tensors[0].dtype)
                    return tensors[0]

                global_shape = _resolve_shape(contexts[0], desc)
                full = _empty_like_global(desc, global_shape, tensors[0].device, type_text)
                full.zero_()
                for context in contexts:
                    local = _get_tensor(context, name)
                    local_shape, offsets = _local_shape_and_offsets(context, desc, global_shape, type_text)
                    if math.prod(local_shape) == 0:
                        continue
                    trailing = max(0, local.ndim - len(local_shape))
                    full[_slice_with_trailing_lanes(offsets, local_shape, trailing)].copy_(local.reshape(tuple(local_shape) + tuple(local.shape[-trailing:] if trailing else ())))
                return full

            def _write_distributed_tensor(contexts, name, value, desc, type_text=None):
                type_text = type_text if type_text is not None else _desc_distributed_type(desc)
                global_shape = _resolve_shape(contexts[0], desc)
                target_shape = _append_vector_lanes_to_shape(global_shape, _desc_vector_lanes(desc, type_text))
                if hasattr(value, "numel") and int(value.numel()) == int(math.prod(target_shape)) and tuple(value.shape) != tuple(target_shape):
                    value = value.reshape(tuple(target_shape))
                shard_axes = _distributed_shard_axes(type_text)
                if not shard_axes:
                    result = None
                    for context in contexts:
                        result = _write_tensor(context, name, value)
                    return result

                result = None
                for context in contexts:
                    local_shape, offsets = _local_shape_and_offsets(context, desc, global_shape, type_text)
                    trailing = max(0, value.ndim - len(global_shape))
                    if math.prod(local_shape) == 0:
                        local = value.new_empty(tuple(local_shape) + tuple(value.shape[-trailing:] if trailing else ()))
                    else:
                        local = value[_slice_with_trailing_lanes(offsets, local_shape, trailing)].contiguous()
                    result = _write_tensor(context, name, local)
                return result

            def _memory_key(desc):
                memory = (desc or {}).get("memory", {})
                def normalize(value):
                    if isinstance(value, dict):
                        if value.get("kind") == "fixed":
                            return str(value.get("value", 0))
                        return json.dumps(value, sort_keys=True)
                    return str(value)
                return (
                    memory.get("location"),
                    str(memory.get("hierarchy", 0)),
                    normalize(memory.get("base_start", 0)),
                    normalize(memory.get("span_start_bytes", 0)),
                    normalize(memory.get("span_size_bytes", 0)),
                )

            def _launch_argument_index(launch_meta, key, desc):
                match = re.fullmatch(r"arg(\d+)", str(key or ""))
                if match:
                    return int(match.group(1))
                name = (desc or {}).get("name")
                if not name:
                    return None
                matches = [index for index, arg in enumerate((launch_meta or {}).get("arguments", [])) if arg == name]
                return matches[0] if len(matches) == 1 else None

            def _launch_output_indices(launch_meta):
                op_name = (launch_meta or {}).get("op_name")
                arguments = list((launch_meta or {}).get("arguments", []))
                if op_name == "matmul":
                    return {2}
                if op_name == "tensor_load":
                    return {0}
                if op_name == "tensor_store":
                    return {1}
                if op_name == "gather_reduce_scatter":
                    return {1}
                if op_name in ("update_paged_attention_kvcache", "update_paged_attention_kv_cache"):
                    return set()
                if op_name == "paged_attention":
                    return {4}
                if op_name == "concat":
                    return {len(arguments) - 1} if arguments else set()
                if (launch_meta or {}).get("kind") == "function":
                    function_id = __nncase_triton_metadata__.get("function_ids", {}).get(op_name)
                    callee_meta = _get_function_metadata(function_id) if function_id is not None else {}
                    parameters = list(callee_meta.get("parameters", []))
                    filtered = _filter_function_argument_items(arguments)
                    outputs = set()
                    for ordinal, (arg_index, _) in enumerate(filtered):
                        if ordinal < len(parameters) and "Out" in str(parameters[ordinal]):
                            outputs.add(int(arg_index))
                    return outputs
                return {len(arguments) - 1} if arguments else set()

            def _is_launch_output_desc(launch_meta, key, desc):
                index = _launch_argument_index(launch_meta, key, desc)
                if index is None:
                    return str(key or "") in ("output", "dest")
                return int(index) in _launch_output_indices(launch_meta)

            def _record_partial_aliases(contexts, launch_meta):
                for key, desc in (launch_meta or {}).get("buffer_arguments", {}).items():
                    if (isinstance(desc, dict)
                        and desc.get("name")
                        and _distributed_is_partial(_desc_distributed_type(desc))
                        and _is_launch_output_desc(launch_meta, key, desc)):
                        key = _memory_key(desc)
                        for context in contexts:
                            context.setdefault("partial_aliases", {})[key] = desc

            def _materialize_partial_aliases(contexts, launch_meta):
                if not contexts:
                    return
                partial_aliases = contexts[0].setdefault("partial_aliases", {})
                for desc in (launch_meta or {}).get("buffer_arguments", {}).values():
                    if not isinstance(desc, dict) or not desc.get("name"):
                        continue
                    if _distributed_is_partial(_desc_distributed_type(desc)):
                        continue
                    key = _memory_key(desc)
                    partial_desc = partial_aliases.get(key)
                    if partial_desc is None:
                        continue
                    full = _materialize_global_tensor(contexts, partial_desc.get("name"), partial_desc, _desc_distributed_type(partial_desc))
                    target_shape = _append_vector_lanes_to_shape(_resolve_shape(contexts[0], desc), _desc_vector_lanes(desc, _desc_distributed_type(desc)))
                    if int(full.numel()) != int(math.prod(target_shape)):
                        continue
                    if tuple(full.shape) != tuple(target_shape):
                        full = full.reshape(tuple(target_shape))
                    _write_distributed_tensor(contexts, desc.get("name"), full, desc, _desc_distributed_type(desc))
                    for context in contexts:
                        context.setdefault("partial_aliases", {}).pop(key, None)

            def _materialize_partial_inputs(contexts, launch_meta):
                if not contexts or (launch_meta or {}).get("op_name") == "gather_reduce_scatter":
                    return
                partial_aliases = contexts[0].setdefault("partial_aliases", {})
                for key, desc in (launch_meta or {}).get("buffer_arguments", {}).items():
                    if not isinstance(desc, dict) or not desc.get("name"):
                        continue
                    if not _distributed_is_partial(_desc_distributed_type(desc)):
                        continue
                    if _is_launch_output_desc(launch_meta, key, desc):
                        continue
                    alias_key = _memory_key(desc)
                    partial_desc = partial_aliases.get(alias_key, desc)
                    full = _materialize_global_tensor(contexts, partial_desc.get("name"), partial_desc, _desc_distributed_type(partial_desc))
                    target_shape = _append_vector_lanes_to_shape(_resolve_shape(contexts[0], desc), _desc_vector_lanes(desc, _desc_distributed_type(desc)))
                    if int(full.numel()) == int(math.prod(target_shape)) and tuple(full.shape) != tuple(target_shape):
                        full = full.reshape(tuple(target_shape))
                    _write_distributed_tensor(contexts, desc.get("name"), full, desc, _desc_distributed_type(desc))
                    for context in contexts:
                        context.setdefault("partial_aliases", {}).pop(alias_key, None)

            def _run_tensor_load_multi(contexts, argument_names, launch_meta):
                dest_name, src_name = argument_names[0], argument_names[1]
                dest_desc = _find_launch_buffer_desc(contexts[0], dest_name, launch_meta, 0)
                if dest_desc is None:
                    return [_execute_launch("boxing", "tensor_load", context, argument_names, True, launch_meta) for context in contexts]
                src = _get_tensor(contexts[0], src_name)
                return _write_distributed_tensor(contexts, dest_name, src, dest_desc, _desc_distributed_type(dest_desc))

            def _run_tensor_store_multi(contexts, argument_names, launch_meta):
                src_name, dest_name = argument_names[0], argument_names[1]
                src_desc = _find_launch_buffer_desc(contexts[0], src_name, launch_meta, 0)
                if src_desc is None:
                    return [_execute_launch("boxing", "tensor_store", context, argument_names, True, launch_meta) for context in contexts]
                full = _materialize_global_tensor(contexts, src_name, src_desc, _desc_distributed_type(src_desc))
                return _write_tensor(contexts[0], dest_name, full)

            def _run_gather_reduce_scatter_multi(contexts, argument_names, launch_meta):
                attrs = (launch_meta or {}).get("op_attrs", {})
                src_name, dest_name = argument_names[0], argument_names[1]
                src_desc = _find_launch_buffer_desc(contexts[0], src_name, launch_meta, 0)
                dest_desc = _find_launch_buffer_desc(contexts[0], dest_name, launch_meta, 1)
                if src_desc is None or dest_desc is None:
                    return [_execute_launch("collective", "gather_reduce_scatter", context, argument_names, True, launch_meta) for context in contexts]
                full = _materialize_global_tensor(contexts, src_name, src_desc, attrs.get("in_type") or _desc_distributed_type(src_desc))
                return _write_distributed_tensor(contexts, dest_name, full, dest_desc, attrs.get("out_type") or _desc_distributed_type(dest_desc))

            def _run_update_kv_multi(contexts, argument_names, launch_meta):
                attrs = (launch_meta or {}).get("op_attrs", {})
                src_name = argument_names[0]
                src_desc = _find_launch_buffer_desc(contexts[0], src_name, launch_meta, 0)
                if src_desc is None:
                    return _run_update_kv(contexts[0], argument_names, attrs)
                full = _materialize_global_tensor(contexts, src_name, src_desc, _desc_distributed_type(src_desc))
                temp_context = dict(contexts[0])
                temp_context["values"] = dict(contexts[0].get("values", {}))
                temp_context["values"][src_name] = full
                return _run_update_kv(temp_context, argument_names, attrs)

            def _run_paged_attention_multi(contexts, argument_names, launch_meta):
                attrs = (launch_meta or {}).get("op_attrs", {})
                q_name = argument_names[0]
                out_name = argument_names[4]
                q_desc = _find_launch_buffer_desc(contexts[0], q_name, launch_meta, 0)
                out_desc = _find_launch_buffer_desc(contexts[0], out_name, launch_meta, 4)
                if q_desc is None or out_desc is None:
                    return [_run_paged_attention(context, argument_names, attrs) for context in contexts]
                full_q = _materialize_global_tensor(contexts, q_name, q_desc, _desc_distributed_type(q_desc))
                temp_context = dict(contexts[0])
                temp_context["values"] = dict(contexts[0].get("values", {}))
                temp_context["values"][q_name] = full_q
                temp_out = _empty_like_global(out_desc, _resolve_shape(contexts[0], out_desc), full_q.device, _desc_distributed_type(out_desc))
                temp_context["values"][out_name] = temp_out
                _run_paged_attention(temp_context, argument_names, attrs)
                return _write_distributed_tensor(contexts, out_name, temp_context["values"][out_name], out_desc, _desc_distributed_type(out_desc))

            def _parallel_pe_enabled():
                value = os.environ.get("NNCASE_CUDA_PARALLEL_PE", "1")
                return str(value).strip().lower() not in ("0", "false", "no", "off")

            def _parallel_pe_min_count():
                value = os.environ.get("NNCASE_CUDA_PARALLEL_PE_MIN", "2")
                try:
                    return max(1, int(value))
                except ValueError:
                    return 2

            def _ensure_pe_streams(contexts):
                if not _parallel_pe_enabled() or len(contexts) < _parallel_pe_min_count():
                    return
                torch = _require_torch()
                if not torch.cuda.is_available():
                    return
                global _PE_STREAMS
                while len(_PE_STREAMS) < len(contexts):
                    _PE_STREAMS.append(torch.cuda.Stream(device=torch.cuda.current_device()))
                for context, stream in zip(contexts, _PE_STREAMS):
                    context["torch_stream"] = stream

            def _synchronize_pe_streams(contexts):
                torch = _TORCH
                if torch is None or not torch.cuda.is_available():
                    return
                streams = []
                for context in contexts:
                    stream = context.get("torch_stream")
                    if stream is not None and all(stream is not existing for existing in streams):
                        streams.append(stream)
                for stream in streams:
                    stream.synchronize()

            def _synchronize_cuda_device():
                torch = _TORCH
                if torch is not None and torch.cuda.is_available():
                    torch.cuda.synchronize()

            def _run_pe_launch_on_context(kind, op_name, context, argument_names, launch_meta):
                stream = context.get("torch_stream")
                torch = _TORCH
                if stream is not None and torch is not None and torch.cuda.is_available():
                    with torch.cuda.stream(stream):
                        return _execute_launch(kind, op_name, context, argument_names, bool(launch_meta.get("requires_collective", False)), launch_meta)
                return _execute_launch(kind, op_name, context, argument_names, bool(launch_meta.get("requires_collective", False)), launch_meta)

            def _run_pe_local_launches(contexts, kind, op_name, argument_names, launch_meta):
                _ensure_pe_streams(contexts)
                if not _parallel_pe_enabled() or len(contexts) < _parallel_pe_min_count() or not any(context.get("torch_stream") is not None for context in contexts):
                    return [
                        _execute_launch(kind, op_name, context, argument_names, bool(launch_meta.get("requires_collective", False)), launch_meta)
                        for context in contexts
                    ]
                result = [
                    _run_pe_launch_on_context(kind, op_name, context, argument_names, launch_meta)
                    for context in contexts
                ]
                _synchronize_pe_streams(contexts)
                return result

            def _multi_pe_contexts(function_id, function_args, stream, all_data_pools, all_output_pools, all_rdata_pools):
                function_meta = _get_function_metadata(function_id)
                pe_count = len(all_data_pools or ())
                if pe_count == 0 or pe_count != len(all_output_pools or ()) or pe_count != len(all_rdata_pools or ()):
                    raise ValueError("multi-PE CUDA/Triton launch requires matching all_data_pools/all_output_pools/all_rdata_pools")
                contexts = []
                for pe in range(pe_count):
                    context = _make_context(
                        pe,
                        int(all_data_pools[pe]),
                        int(all_output_pools[pe]),
                        int(all_rdata_pools[pe]),
                        function_args,
                        stream,
                        function_meta,
                        all_data_pools,
                        all_output_pools,
                        all_rdata_pools)
                    _bind_function_args(context, function_meta.get("parameters", []), function_args)
                    contexts.append(context)
                return function_meta, contexts

            def _selected_multi_pe_launches(function_meta, contexts):
                ordered = sorted(function_meta.get("launches", []), key=lambda launch: int(launch.get("ordinal", 0)))
                is_shape_bucket_entry = (
                    function_meta.get("is_entry")
                    and len(ordered) > 1
                    and all(launch.get("kind") == "function" and str(launch.get("op_name", "")).startswith("main_segment_") for launch in ordered)
                )
                if not is_shape_bucket_entry:
                    return ordered
                selected = _select_shape_bucket_launch(
                    function_meta,
                    [int(launch.get("ordinal", 0)) for launch in ordered],
                    int(_symbol_env(contexts[0]).get("sequence_length", 0)))
                return [launch for launch in ordered if int(launch.get("ordinal", 0)) == selected]

            def _execute_multi_pe_nested_function(contexts, launch_meta):
                op_name = launch_meta.get("op_name")
                function_id = contexts[0]["module_metadata"].get("function_ids", {}).get(op_name)
                if function_id is None:
                    raise KeyError(f"unknown nested cuda triton function: {op_name}")
                callee_meta = _get_function_metadata(function_id)
                argument_names = list(launch_meta.get("arguments", []))
                filtered = _filter_function_argument_items(argument_names)
                filtered_names = _filter_function_argument_names(argument_names)
                expected = len(callee_meta.get("parameters", []))
                if len(filtered_names) != expected:
                    raise ValueError(f"nested function {op_name} expects {expected} filtered args, got {len(filtered_names)} from {argument_names}")
                callee_contexts = []
                for context in contexts:
                    context["current_launch_metadata"] = launch_meta
                    nested_args = tuple(_resolve_nested_argument(context, name, index, launch_meta) for index, name in filtered)
                    callee_context = _make_context(
                        context["pe_id"],
                        context["data_pool"],
                        context["output_pool"],
                        context["rdata_pool"],
                        nested_args,
                        context["stream"],
                        callee_meta,
                        context.get("all_data_pools"),
                        context.get("all_output_pools"),
                        context.get("all_rdata_pools"))
                    callee_context["symbol_env"].update(_symbol_env(context))
                    _bind_function_args(callee_context, callee_meta.get("parameters", []), nested_args)
                    callee_contexts.append(callee_context)
                return _execute_multi_pe_function_contexts(callee_meta, callee_contexts)

            def _execute_multi_pe_launch_body(contexts, launch_meta):
                kind = launch_meta.get("kind")
                op_name = launch_meta.get("op_name")
                argument_names = list(launch_meta.get("arguments", []))
                for context in contexts:
                    context["current_launch_metadata"] = launch_meta
                    context["launches"].append(launch_meta)
                if any(context.get("partial_aliases") for context in contexts):
                    _synchronize_pe_streams(contexts)
                _materialize_partial_aliases(contexts, launch_meta)
                _materialize_partial_inputs(contexts, launch_meta)
                if kind == "function":
                    result = _execute_multi_pe_nested_function(contexts, launch_meta)
                    _record_partial_aliases(contexts, launch_meta)
                    return result
                if op_name == "tensor_load":
                    _synchronize_pe_streams(contexts)
                    result = _run_tensor_load_multi(contexts, argument_names, launch_meta)
                    _synchronize_cuda_device()
                    _record_partial_aliases(contexts, launch_meta)
                    return result
                if op_name == "tensor_store":
                    _synchronize_pe_streams(contexts)
                    result = _run_tensor_store_multi(contexts, argument_names, launch_meta)
                    _synchronize_cuda_device()
                    _record_partial_aliases(contexts, launch_meta)
                    return result
                if op_name == "gather_reduce_scatter":
                    _synchronize_pe_streams(contexts)
                    result = _run_gather_reduce_scatter_multi(contexts, argument_names, launch_meta)
                    _synchronize_cuda_device()
                    _record_partial_aliases(contexts, launch_meta)
                    return result
                if op_name in ("update_paged_attention_kvcache", "update_paged_attention_kv_cache"):
                    _synchronize_pe_streams(contexts)
                    result = _run_update_kv_multi(contexts, argument_names, launch_meta)
                    _synchronize_cuda_device()
                    _record_partial_aliases(contexts, launch_meta)
                    return result
                if op_name == "paged_attention":
                    _synchronize_pe_streams(contexts)
                    result = _run_paged_attention_multi(contexts, argument_names, launch_meta)
                    _synchronize_cuda_device()
                    _record_partial_aliases(contexts, launch_meta)
                    return result
                result = _run_pe_local_launches(contexts, kind, op_name, argument_names, launch_meta)
                _record_partial_aliases(contexts, launch_meta)
                return result

            def _execute_multi_pe_launch(contexts, launch_meta):
                kind = launch_meta.get("kind")
                op_name = launch_meta.get("op_name")
                argument_names = list(launch_meta.get("arguments", []))
                event = _verbose_launch_begin(contexts, kind, op_name, argument_names, launch_meta)
                previous = []
                for context in contexts:
                    previous.append(context.get("_suppress_launch_verbose", False))
                    context["_suppress_launch_verbose"] = True
                try:
                    return _execute_multi_pe_launch_body(contexts, launch_meta)
                finally:
                    for context, value in zip(contexts, previous):
                        if value:
                            context["_suppress_launch_verbose"] = value
                        else:
                            context.pop("_suppress_launch_verbose", None)
                    _verbose_launch_end(event)

            def _execute_multi_pe_function_contexts(function_meta, contexts):
                for launch_meta in _selected_multi_pe_launches(function_meta, contexts):
                    _execute_multi_pe_launch(contexts, launch_meta)
                return contexts[0]

            def _execute_multi_pe_function(function_id, *function_args, stream=None, all_data_pools=None, all_output_pools=None, all_rdata_pools=None):
                function_meta, contexts = _multi_pe_contexts(function_id, function_args, stream, tuple(all_data_pools or ()), tuple(all_output_pools or ()), tuple(all_rdata_pools or ()))
                _entry_begin(function_meta, function_args)
                try:
                    return _execute_multi_pe_function_contexts(function_meta, contexts)
                finally:
                    _entry_end(function_meta)

            def _transpose_to_shape(value, output):
                if value.ndim == output.ndim:
                    for perm in __import__("itertools").permutations(range(value.ndim)):
                        if tuple(value.shape[i] for i in perm) == tuple(output.shape):
                            return value.permute(*perm).contiguous()
                if value.numel() == output.numel():
                    return value.reshape(tuple(output.shape))
                return value

            def _run_matmul(context, args, attrs):
                lhs = _get_tensor(context, args[0])
                rhs = _get_tensor(context, args[1])
                try:
                    out = _get_tensor(context, args[2])
                except KeyError:
                    out = None
                if attrs.get("transpose_a"):
                    lhs = lhs.transpose(-2, -1)
                if attrs.get("transpose_b"):
                    rhs = rhs.transpose(-2, -1)
                compute_dtype = out.dtype if out is not None else lhs.dtype
                if compute_dtype is _require_torch().float32:
                    lhs = lhs.float()
                    rhs = rhs.float()
                result = lhs.matmul(rhs)
                scale = _get_tensor(context, args[4]) if len(args) > 4 else None
                if scale is not None:
                    result = result * scale
                # AutoTiling may lower matmul loadC to an unmaterialized scalar expression.
                # The CUDA PoC fallback runs one full-buffer matmul per launch, so it is not
                # a tile-loop accumulation point.
                if len(args) > 3 and args[3] == "call":
                    load_c = False
                else:
                    load_c = _get_tensor(context, args[3]) if len(args) > 3 else None
                if load_c is True:
                    if out is None:
                        out = _get_tensor(context, args[2], result)
                    result = result + out
                elif hasattr(load_c, "shape") and load_c.dtype is not _require_torch().bool:
                    result = result + load_c
                if out is None:
                    compute_dtype = result.dtype
                return _write_tensor(context, args[2], result.to(compute_dtype))

            def _run_layer_norm(context, args, attrs):
                torch = _require_torch()
                x = _get_tensor(context, args[0]).float()
                scale = _get_tensor(context, args[1]).float()
                bias = _get_tensor(context, args[2]).float()
                axis = int(attrs.get("axis", -1))
                eps = float(attrs.get("epsilon", 1e-5))
                use_mean = bool(attrs.get("use_mean", True))
                dims = tuple(range(axis if axis >= 0 else x.ndim + axis, x.ndim))
                if use_mean:
                    mean = x.mean(dim=dims, keepdim=True)
                    var = (x - mean).pow(2).mean(dim=dims, keepdim=True)
                    y = (x - mean) * torch.rsqrt(var + eps)
                else:
                    var = x.pow(2).mean(dim=dims, keepdim=True)
                    y = x * torch.rsqrt(var + eps)
                while scale.ndim < y.ndim:
                    scale = scale.unsqueeze(0)
                    bias = bias.unsqueeze(0)
                return _write_tensor(context, args[4], y * scale + bias)

            def _run_rope(context, args):
                torch = _require_torch()
                x = _get_tensor(context, args[0]).float()
                cos = _get_tensor(context, args[1]).float()
                sin = _get_tensor(context, args[2]).float()
                out = _get_tensor(context, args[3], x)
                if x.ndim == 3 and cos.ndim == 2 and int(x.shape[-1]) == int(cos.shape[-1]):
                    head, seq, dim = x.shape
                    half = dim // 2
                    cos = cos.reshape(seq, dim)
                    sin = sin.reshape(seq, dim)
                    first = x[:, :, :half]
                    second = x[:, :, half:]
                    y = torch.empty_like(x)
                    y[:, :, :half] = first * cos[:, :half].unsqueeze(0) - second * sin[:, :half].unsqueeze(0)
                    y[:, :, half:] = second * cos[:, half:].unsqueeze(0) + first * sin[:, half:].unsqueeze(0)
                else:
                    head, dim, seq = x.shape
                    half = dim // 2
                    if cos.ndim == 2 and tuple(cos.shape) == (seq, dim):
                        cos = cos.transpose(0, 1)
                        sin = sin.transpose(0, 1)
                    cos = cos.reshape(dim, seq)
                    sin = sin.reshape(dim, seq)
                    first = x[:, :half, :]
                    second = x[:, half:, :]
                    y = torch.empty_like(x)
                    y[:, :half, :] = first * cos[:half, :].unsqueeze(0) - second * sin[:half, :].unsqueeze(0)
                    y[:, half:, :] = second * cos[half:, :].unsqueeze(0) + first * sin[half:, :].unsqueeze(0)
                return _write_tensor(context, args[3], y.to(out.dtype))

            def _run_get_position_ids(context, args):
                torch = _require_torch()
                out = _get_tensor(context, args[1])
                start = int(_KV_STATE.get("current_start", 0))
                local_offset = 0
                desc = _find_launch_buffer_desc(context, args[1], context.get("current_launch_metadata"), 1)
                if desc is None:
                    bound = context.get("bound_args", {}).get(_strip_l0(args[1]))
                    if isinstance(bound, _BufferRef):
                        desc = bound.desc
                if desc is not None:
                    global_shape = _resolve_shape(context, desc)
                    _, offsets = _local_shape_and_offsets(context, desc, global_shape, _desc_distributed_type(desc))
                    shard_axes = _distributed_shard_axes(_desc_distributed_type(desc))
                    if shard_axes:
                        local_offset = int(offsets[int(shard_axes[0])])
                values = torch.arange(start + local_offset, start + local_offset + out.numel(), device=out.device, dtype=out.dtype)
                return _write_tensor(context, args[1], values.reshape(tuple(out.shape)))

            def _run_pack(context, args, attrs):
                value = _get_tensor(context, args[0])
                lanes = tuple(int(x) for x in attrs.get("lanes", []) or ())
                axes = tuple(int(x) for x in attrs.get("axes", []) or ())
                if len(lanes) != len(axes):
                    raise ValueError(f"pack lanes/axes mismatch: lanes={lanes} axes={axes}")
                result = value
                old_lanes_count = len(_vector_lanes_for_name(context, args[0]))
                for index in range(len(axes) - 1, -1, -1):
                    lane = int(lanes[index])
                    axis = int(axes[index])
                    if axis < 0:
                        continue
                    shape = list(result.shape)
                    if int(shape[axis]) % lane != 0:
                        raise ValueError(f"pack axis {axis} shape {tuple(shape)} is not divisible by lane {lane}")
                    divided_shape = shape[:axis] + [int(shape[axis]) // lane, lane] + shape[axis + 1:]
                    result = result.reshape(tuple(divided_shape))
                    rank = len(divided_shape)
                    middle_count = rank - (axis + old_lanes_count + 2)
                    perm = (
                        list(range(0, axis + 1))
                        + list(range(axis + 2, axis + 2 + max(0, middle_count)))
                        + [axis + 1]
                        + list(range(rank - old_lanes_count, rank))
                    )
                    result = result.permute(*perm).contiguous()
                    old_lanes_count += 1
                return _write_tensor(context, args[1], result)

            def _run_unpack(context, args, attrs):
                value = _get_tensor(context, args[0])
                axes = tuple(int(x) for x in attrs.get("axes", []) or ())
                result = value
                old_lanes_count = len(_vector_lanes_for_name(context, args[0]))
                if old_lanes_count == 0 and attrs.get("lanes"):
                    old_lanes_count = len(attrs.get("lanes") or [])
                for axis in axes:
                    axis = int(axis)
                    if old_lanes_count <= 0:
                        raise ValueError(f"unpack requires vector lanes for {args[0]}")
                    perm = list(range(result.ndim))
                    tail = perm[-(old_lanes_count - 1):] if old_lanes_count > 1 else []
                    perm = perm[:axis + 1] + [perm[-old_lanes_count]] + perm[axis + 1:-old_lanes_count] + tail
                    result = result.permute(*perm).contiguous()
                    shape = list(result.shape)
                    shape[axis] = int(shape[axis]) * int(shape[axis + 1])
                    del shape[axis + 1]
                    result = result.reshape(tuple(shape))
                    old_lanes_count -= 1
                return _write_tensor(context, args[1], result)

            def _merge_layout_vector_lanes(tensor, layout):
                layout = list(layout or ["Head", "Dim", "Seq"])
                logical_rank = len(layout)
                if tensor.ndim <= logical_rank:
                    return tensor
                dim_axis = layout.index("Dim") if "Dim" in layout else logical_rank - 1
                result = tensor
                while result.ndim > logical_rank:
                    lane_axis = result.ndim - 1
                    perm = list(range(result.ndim))
                    lane = perm.pop(lane_axis)
                    perm.insert(dim_axis + 1, lane)
                    result = result.permute(*perm).contiguous()
                    shape = list(result.shape)
                    shape[dim_axis] = int(shape[dim_axis]) * int(shape[dim_axis + 1])
                    del shape[dim_axis + 1]
                    result = result.reshape(tuple(shape))
                return result

            def _split_layout_vector_lanes(tensor, layout, output):
                if output is None or not hasattr(output, "shape"):
                    return tensor
                layout = list(layout or ["Head", "Dim", "Seq"])
                logical_rank = len(layout)
                target = tuple(output.shape)
                if len(target) <= logical_rank or tuple(tensor.shape) == target:
                    return tensor
                if int(tensor.numel()) != math.prod(target):
                    return tensor.reshape(target)
                dim_axis = layout.index("Dim") if "Dim" in layout else logical_rank - 1
                result = tensor
                for lane in target[logical_rank:]:
                    lane = int(lane)
                    shape = list(result.shape)
                    if int(shape[dim_axis]) % lane != 0:
                        return tensor.reshape(target)
                    divided_shape = shape[:dim_axis] + [int(shape[dim_axis]) // lane, lane] + shape[dim_axis + 1:]
                    result = result.reshape(tuple(divided_shape))
                    rank = len(divided_shape)
                    perm = list(range(0, dim_axis + 1)) + list(range(dim_axis + 2, rank)) + [dim_axis + 1]
                    result = result.permute(*perm).contiguous()
                return result.reshape(target)

            def _layout_to_hds(tensor, layout):
                layout = list(layout or ["Head", "Dim", "Seq"])
                tensor = _merge_layout_vector_lanes(tensor, layout)
                order = [layout.index("Head"), layout.index("Dim"), layout.index("Seq")]
                return tensor.permute(*order).contiguous()

            def _from_hds(tensor, layout, output=None):
                layout = list(layout or ["Head", "Dim", "Seq"])
                inverse = [0, 0, 0]
                for target_axis, name in enumerate(["Head", "Dim", "Seq"]):
                    inverse[layout.index(name)] = target_axis
                result = tensor.permute(*inverse).contiguous()
                return _split_layout_vector_lanes(result, layout, output)

            def _run_update_kv(context, args, attrs):
                torch = _require_torch()
                value = _layout_to_hds(_get_tensor(context, args[0]), attrs.get("layout")).detach()
                layer = int(attrs.get("layer_id", 0))
                kind = str(attrs.get("cache_kind", "Key")).lower()
                key = (layer, kind)
                old = _KV_STATE["cache"].get(key)
                start = int(_KV_STATE.get("current_start", 0))
                end = start + int(value.shape[2])
                if old is None:
                    old = torch.empty((value.shape[0], value.shape[1], end), dtype=value.dtype, device=value.device)
                elif int(old.shape[2]) < end:
                    grown = torch.empty((old.shape[0], old.shape[1], end), dtype=old.dtype, device=old.device)
                    grown[:, :, :old.shape[2]].copy_(old)
                    old = grown
                old[:, :, start:end].copy_(value.to(old.dtype))
                _KV_STATE["cache"][key] = old
                return None

            def _run_paged_attention(context, args, attrs):
                torch = _require_torch()
                q = _layout_to_hds(_get_tensor(context, args[0]).float(), attrs.get("layout"))
                out = _get_tensor(context, args[4], q)
                layer = int(attrs.get("layer_id", 0))
                k = _KV_STATE["cache"].get((layer, "key"))
                v = _KV_STATE["cache"].get((layer, "value"))
                if k is None or v is None:
                    raise RuntimeError(f"missing CUDA/Triton KV cache for layer {layer}")
                k = k.float()
                v = v.float()
                end = int(_KV_STATE.get("current_start", 0)) + int(q.shape[2])
                end = min(end, int(k.shape[2]), int(v.shape[2]))
                k = k[:, :, :end]
                v = v[:, :, :end]
                repeat = max(1, q.shape[0] // k.shape[0])
                k = k.repeat_interleave(repeat, dim=0)
                v = v.repeat_interleave(repeat, dim=0)
                scale_arg = _get_tensor(context, args[3])
                scale = float(scale_arg.reshape(-1)[0].item()) if hasattr(scale_arg, "shape") else float(scale_arg)
                scores = torch.einsum("hdt,hds->hts", q, k) * scale
                start = int(_KV_STATE.get("current_start", 0))
                t = q.shape[2]
                s = k.shape[2]
                query_pos = torch.arange(start, start + t, device=scores.device).view(1, t, 1)
                key_pos = torch.arange(0, s, device=scores.device).view(1, 1, s)
                scores = scores.masked_fill(key_pos > query_pos, -torch.inf)
                probs = torch.softmax(scores, dim=-1)
                y = torch.einsum("hts,hds->hdt", probs, v)
                y = _from_hds(y, attrs.get("layout"), out)
                return _write_tensor(context, args[4], y.to(out.dtype))

            def _run_gather(context, args, attrs):
                src = _get_tensor(context, args[0])
                index = _get_tensor(context, args[1]).long()
                axis = int(attrs.get("axis", 0))
                result = src.index_select(axis, index.reshape(-1))
                expected = _get_tensor(context, args[2], result)
                if result.numel() == expected.numel():
                    result = result.reshape(tuple(expected.shape))
                return _write_tensor(context, args[2], result)

            def _infer_concat_axis(inputs, output):
                out_shape = tuple(output.shape)
                for axis in range(len(out_shape)):
                    total = 0
                    matched = True
                    for tensor in inputs:
                        shape = tuple(tensor.shape)
                        if len(shape) != len(out_shape):
                            matched = False
                            break
                        total += int(shape[axis])
                        for dim, (lhs, rhs) in enumerate(zip(shape, out_shape)):
                            if dim != axis and int(lhs) != int(rhs):
                                matched = False
                                break
                        if not matched:
                            break
                    if matched and total == int(out_shape[axis]):
                        return axis
                return 0

            def _run_concat(context, args, attrs):
                torch = _require_torch()
                inputs = [_get_tensor(context, name) for name in args[:-1]]
                out = _get_tensor(context, args[-1], inputs[0] if inputs else None)
                axis = int(attrs["axis"]) if "axis" in attrs else _infer_concat_axis(inputs, out)
                result = torch.cat([tensor.to(out.dtype) for tensor in inputs], dim=axis)
                if tuple(result.shape) != tuple(out.shape) and int(result.numel()) == int(out.numel()):
                    result = result.reshape(tuple(out.shape))
                return _write_tensor(context, args[-1], result)

            def _triton_verbose_enabled():
                value = os.environ.get("NNCASE_TRITON_VERBOSE") or os.environ.get("NNCASE_TRITON_VERBOSES") or os.environ.get("NNCASE_CUDA_VERBOSE") or ""
                return str(value).strip().lower() in ("1", "true", "yes", "on", "verbose")

            def _triton_verbose_limit():
                value = os.environ.get("NNCASE_TRITON_VERBOSE_LIMIT", "0")
                try:
                    return max(0, int(value))
                except ValueError:
                    return 0

            def _verbose_contexts(context_or_contexts):
                if isinstance(context_or_contexts, (list, tuple)):
                    return list(context_or_contexts)
                return [context_or_contexts]

            def _verbose_format_shape(shape):
                if shape is None:
                    return "?"
                return "(" + ",".join(str(int(dim)) for dim in shape) + ")"

            def _verbose_format_arg(context, name, ordinal, launch_meta):
                desc = _find_launch_buffer_desc(context, name, launch_meta, ordinal)
                if desc is None:
                    bound = context.get("bound_args", {}).get(_strip_l0(name))
                    if isinstance(bound, _BufferRef):
                        desc = bound.desc
                    elif bound is not None:
                        try:
                            shape = _bound_shape(context, bound)
                            return f"{name}:shape={_verbose_format_shape(shape)}"
                        except Exception:
                            return str(name)
                if desc is None:
                    return str(name)
                try:
                    shape = _resolve_shape(context, desc)
                except Exception:
                    shape = None
                memory = desc.get("memory", {})
                dtype = desc.get("dtype", "?")
                location = memory.get("location", "?")
                distributed_type = _desc_distributed_type(desc)
                if distributed_type:
                    return f"{name}:shape={_verbose_format_shape(shape)} dtype={dtype} mem={location} dist={distributed_type}"
                return f"{name}:shape={_verbose_format_shape(shape)} dtype={dtype} mem={location}"

            def _verbose_format_attrs(attrs):
                if not attrs:
                    return "{}"
                keys = (
                    "func_name",
                    "c_source_path",
                    "layer_id",
                    "cache_kind",
                    "axis",
                    "perm",
                    "transpose_a",
                    "transpose_b",
                    "fused_reduce",
                    "in_type",
                    "out_type",
                )
                selected = {key: attrs.get(key) for key in keys if key in attrs}
                return json.dumps(selected, ensure_ascii=False, sort_keys=True)

            def _verbose_launch_begin(context_or_contexts, kind, op_name, argument_names, launch_meta):
                global _TRITON_VERBOSE_COUNT, _TRITON_VERBOSE_LIMIT_REPORTED
                if not _triton_verbose_enabled():
                    return None
                limit = _triton_verbose_limit()
                if limit > 0 and _TRITON_VERBOSE_COUNT >= limit:
                    if not _TRITON_VERBOSE_LIMIT_REPORTED:
                        print(f"[nncase-triton] verbose limit reached ({limit}); suppressing remaining launches", flush=True)
                        _TRITON_VERBOSE_LIMIT_REPORTED = True
                    return None
                _TRITON_VERBOSE_COUNT += 1
                contexts = _verbose_contexts(context_or_contexts)
                context = contexts[0] if contexts else {}
                pe_count = len(contexts) if len(contexts) > 1 else int(context.get("module_metadata", {}).get("pe_count", 1) or 1)
                function_name = context.get("function_metadata", {}).get("name", "?")
                ordinal = (launch_meta or {}).get("ordinal", "?")
                attrs = (launch_meta or {}).get("op_attrs", {})
                args = ", ".join(_verbose_format_arg(context, name, index, launch_meta or {}) for index, name in enumerate(argument_names or []))
                grid = (pe_count, 1, 1)
                block = (1, 1, 1)
                collective = bool((launch_meta or {}).get("requires_collective", False) or kind == "collective")
                print(
                    f"[nncase-triton] begin function={function_name} ordinal={ordinal} kind={kind} op={op_name} "
                    f"launch<grid={grid}, block={block}> pe_count={pe_count} collective={collective} "
                    f"args=[{args}] attrs={_verbose_format_attrs(attrs)}",
                    flush=True)
                return {"start": time.perf_counter(), "function": function_name, "ordinal": ordinal, "kind": kind, "op": op_name}

            def _verbose_launch_end(event):
                if event is None:
                    return
                elapsed_ms = (time.perf_counter() - event["start"]) * 1000.0
                print(
                    f"[nncase-triton] end function={event['function']} ordinal={event['ordinal']} "
                    f"kind={event['kind']} op={event['op']} elapsed_ms={elapsed_ms:.3f}",
                    flush=True)

            def _execute_launch(kind, op_name, context, argument_names, separate, launch_meta):
                if context.get("_suppress_launch_verbose"):
                    return _execute_launch_body(kind, op_name, context, argument_names, separate, launch_meta)
                event = _verbose_launch_begin(context, kind, op_name, argument_names, launch_meta)
                try:
                    return _execute_launch_body(kind, op_name, context, argument_names, separate, launch_meta)
                finally:
                    _verbose_launch_end(event)

            def _execute_launch_body(kind, op_name, context, argument_names, separate, launch_meta):
                context["current_launch_metadata"] = launch_meta or {}
                attrs = (launch_meta or {}).get("op_attrs", {})
                if op_name in ("memcopy", "tensor_load", "gather_reduce_scatter"):
                    return _copy_tensor(context, argument_names[0], argument_names[1])
                if op_name == "tensor_store":
                    return _copy_tensor(context, argument_names[1], argument_names[0])
                if op_name == "matmul":
                    return _run_matmul(context, argument_names, attrs)
                if op_name == "vectorized_layer_norm":
                    return _run_layer_norm(context, argument_names, attrs)
                if op_name == "gather":
                    return _run_gather(context, argument_names, attrs)
                if op_name == "transpose":
                    src = _get_tensor(context, argument_names[0])
                    out = _get_tensor(context, argument_names[1], src)
                    perm = attrs.get("perm")
                    result = src.permute(*perm).contiguous() if perm else _transpose_to_shape(src, out)
                    return _write_tensor(context, argument_names[1], result)
                if op_name in ("ro_pe", "rope"):
                    return _run_rope(context, argument_names)
                if op_name == "get_position_ids":
                    return _run_get_position_ids(context, argument_names)
                if op_name == "concat":
                    return _run_concat(context, argument_names, attrs)
                if op_name == "pack":
                    return _run_pack(context, argument_names, attrs)
                if op_name == "unpack":
                    return _run_unpack(context, argument_names, attrs)
                if op_name in ("update_paged_attention_kvcache", "update_paged_attention_kv_cache"):
                    return _run_update_kv(context, argument_names, attrs)
                if op_name == "paged_attention":
                    return _run_paged_attention(context, argument_names, attrs)
                if op_name == "swish":
                    torch = _require_torch()
                    x = _get_tensor(context, argument_names[0])
                    beta = float(attrs.get("beta", 1.0))
                    return _write_tensor(context, argument_names[1], x * torch.sigmoid(x * beta))
                if op_name.startswith("elementwise."):
                    torch = _require_torch()
                    if op_name == "elementwise.cast":
                        x = _get_tensor(context, argument_names[0])
                        dtype = _dtype_from_name(attrs.get("new_type", "DataTypes.Float32"))
                        return _write_tensor(context, argument_names[1], x.to(dtype))
                    if op_name == "elementwise.add":
                        return _write_tensor(context, argument_names[2], _get_tensor(context, argument_names[0]) + _get_tensor(context, argument_names[1]))
                    if op_name == "elementwise.mul":
                        return _write_tensor(context, argument_names[2], _get_tensor(context, argument_names[0]) * _get_tensor(context, argument_names[1]))
                    if op_name == "elementwise.where":
                        return _write_tensor(context, argument_names[3], torch.where(_get_tensor(context, argument_names[0]).bool(), _get_tensor(context, argument_names[1]), _get_tensor(context, argument_names[2])))
                    if op_name == "elementwise.compare.equal":
                        return _write_tensor(context, argument_names[2], _get_tensor(context, argument_names[0]) == _get_tensor(context, argument_names[1]))
                    if op_name == "elementwise.cos":
                        return _write_tensor(context, argument_names[1], torch.cos(_get_tensor(context, argument_names[0])))
                    if op_name == "elementwise.sin":
                        return _write_tensor(context, argument_names[1], torch.sin(_get_tensor(context, argument_names[0])))
                raise NotImplementedError(f"unsupported CUDA/Triton launch {kind}:{op_name} args={argument_names}")

            def _entry_begin(function_meta, function_args):
                if not function_meta.get("is_entry"):
                    return
                _KV_STATE["entry_depth"] += 1
                if _KV_STATE["entry_depth"] == 1 and function_args:
                    seq_len = int(function_args[0][1][0]) if isinstance(function_args[0], tuple) and len(function_args[0]) >= 2 else 0
                    _KV_STATE["current_start"] = int(_KV_STATE.get("total_tokens", 0))
                    _KV_STATE["current_length"] = seq_len

            def _entry_end(function_meta):
                if not function_meta.get("is_entry"):
                    return
                if _KV_STATE["entry_depth"] == 1:
                    _KV_STATE["total_tokens"] = int(_KV_STATE.get("total_tokens", 0)) + int(_KV_STATE.get("current_length", 0))
                _KV_STATE["entry_depth"] = max(0, _KV_STATE["entry_depth"] - 1)

            """);
    }

    public string BuildMetadataJson(CudaTritonModuleSource module)
    {
        var dataPoolSize = module.Functions.Count == 0 ? 0 : module.Functions.Max(f => f.LocalDataPoolSize);
        var outputPoolSize = module.Functions.Count == 0 ? 0 : module.Functions.Max(f => f.OutputPoolSize);
        var blockLocalDataPoolSize = module.Functions.Count == 0 ? 0 : module.Functions.Max(f => f.BlockLocalDataPoolSize);
        var poolBytesPerPe = Max(
            dataPoolSize,
            outputPoolSize,
            module.RdataPoolSize,
            module.ThreadLocalRdataPoolSize,
            module.BlockLocalRdataPoolSize,
            blockLocalDataPoolSize);
        var cclScratchBytes = 0UL;
        var sb = new StringBuilder();
        sb.AppendLine("{");
        sb.AppendLine("  \"schema_version\": 1,");
        sb.AppendLine("  \"device_id\": 0,");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  \"pe_count\": {module.PeCount},");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  \"pool_bytes_per_pe\": {poolBytesPerPe},");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  \"ccl_scratch_bytes\": {cclScratchBytes},");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  \"data_pool_size\": {dataPoolSize},");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  \"output_pool_size\": {outputPoolSize},");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  \"rdata_pool_size\": {module.RdataPoolSize},");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  \"thread_local_rdata_pool_size\": {module.ThreadLocalRdataPoolSize},");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  \"block_local_rdata_pool_size\": {module.BlockLocalRdataPoolSize},");
        sb.AppendLine(CultureInfo.InvariantCulture, $"  \"block_local_data_pool_size\": {blockLocalDataPoolSize},");
        sb.AppendLine($"  \"function_ids\": {{{string.Join(", ", module.Functions.Select(f => $"{Quote(f.Name)}: {f.Id.ToString(CultureInfo.InvariantCulture)}"))}}},");
        sb.AppendLine("  \"functions\": [");
        for (int i = 0; i < module.Functions.Count; i++)
        {
            var function = module.Functions[i];
            sb.AppendLine("    {");
            sb.AppendLine(CultureInfo.InvariantCulture, $"      \"id\": {function.Id},");
            sb.AppendLine($"      \"name\": {Quote(function.Name)},");
            sb.AppendLine($"      \"is_entry\": {JsonBool(function.IsEntry)},");
            sb.AppendLine($"      \"parameters\": [{string.Join(", ", function.Parameters.Select(Quote))}],");
            sb.AppendLine($"      \"parameter_descriptors\": {BuildParameterDescArray(function.ParameterDescs)},");
            sb.AppendLine($"      \"buffers\": {BuildBufferMap(function.Buffers)},");
            sb.AppendLine(CultureInfo.InvariantCulture, $"      \"data_pool_size\": {function.LocalDataPoolSize},");
            sb.AppendLine(CultureInfo.InvariantCulture, $"      \"output_pool_size\": {function.OutputPoolSize},");
            sb.AppendLine(CultureInfo.InvariantCulture, $"      \"rdata_pool_size\": {function.RdataPoolSize},");
            sb.AppendLine(CultureInfo.InvariantCulture, $"      \"block_local_data_pool_size\": {function.BlockLocalDataPoolSize},");
            sb.AppendLine($"      \"returns\": {BuildReturnDescArray(function.Returns)},");
            sb.AppendLine("      \"launches\": [");
            for (int j = 0; j < function.Launches.Count; j++)
            {
                var launch = function.Launches[j];
                sb.Append("        {");
                sb.Append(CultureInfo.InvariantCulture, $"\"ordinal\": {launch.Ordinal}, ");
                sb.Append($"\"kind\": {Quote(ToPythonKind(launch.Kind))}, ");
                sb.Append($"\"op_name\": {Quote(launch.OpName)}, ");
                sb.Append($"\"arguments\": [{string.Join(", ", launch.Arguments.Select(Quote))}], ");
                sb.Append($"\"buffer_arguments\": {BuildBufferMap(launch.BufferArguments)}, ");
                sb.Append($"\"op_attrs\": {BuildAttributeMap(launch.OpAttributes)}, ");
                sb.Append($"\"requires_collective\": {JsonBool(launch.RequiresCollective)}");
                sb.Append('}');
                sb.AppendLine(j == function.Launches.Count - 1 ? string.Empty : ",");
            }

            sb.AppendLine("      ]");
            sb.Append("    }");
            sb.AppendLine(i == module.Functions.Count - 1 ? string.Empty : ",");
        }

        sb.AppendLine("  ]");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void WriteLaunchHelper(StringBuilder sb, string kind)
    {
        sb.AppendLine($"def _launch_{kind}(op_name, context, argument_names, separate=False, launch_meta=None):");
        sb.AppendLine($"    return _record_launch({Quote(kind)}, op_name, context, argument_names, separate, launch_meta)");
        sb.AppendLine();
    }

    private static void WriteFunctionInvoker(StringBuilder sb, CudaTritonFunctionSource function)
    {
        var invokerName = GetInvokerName(function.Name);
        var orderedLaunches = function.Launches.OrderBy(l => l.Ordinal).ToArray();
        var isShapeBucketEntry = function.IsEntry
            && orderedLaunches.Length > 1
            && orderedLaunches.All(l => l.Kind == CudaTritonLaunchKind.Function && l.OpName.StartsWith("main_segment_", StringComparison.Ordinal));
        sb.AppendLine($"def {invokerName}(pe_id, data_pool, output_pool, rdata_pool, *function_args, stream=None, all_data_pools=None, all_output_pools=None, all_rdata_pools=None):");
        sb.AppendLine($"    function_meta = _get_function_metadata({function.Id.ToString(CultureInfo.InvariantCulture)})");
        sb.AppendLine("    context = _make_context(pe_id, data_pool, output_pool, rdata_pool, function_args, stream, function_meta, all_data_pools, all_output_pools, all_rdata_pools)");
        sb.AppendLine($"    _bind_function_args(context, [{string.Join(", ", function.Parameters.Select(Quote))}], function_args)");
        sb.AppendLine("    _entry_begin(function_meta, function_args)");
        sb.AppendLine("    try:");
        if (isShapeBucketEntry)
        {
            sb.AppendLine($"        _selected_shape_bucket_ordinal = _select_shape_bucket_launch(function_meta, [{string.Join(", ", orderedLaunches.Select(l => l.Ordinal.ToString(CultureInfo.InvariantCulture)))}], int(_symbol_env(context).get(\"sequence_length\", 0)))");
            sb.AppendLine("        _shape_bucket_matched = False");
            foreach (var launch in orderedLaunches)
            {
                sb.AppendLine($"        if _selected_shape_bucket_ordinal == {launch.Ordinal.ToString(CultureInfo.InvariantCulture)}:");
                sb.AppendLine("            _shape_bucket_matched = True");
                sb.AppendLine($"            _launch_{ToPythonKind(launch.Kind)}({Quote(launch.OpName)}, context, [{string.Join(", ", launch.Arguments.Select(Quote))}], separate={ToPythonBool(launch.RequiresCollective)}, launch_meta=_get_launch_metadata(function_meta, {launch.Ordinal.ToString(CultureInfo.InvariantCulture)}))");
            }

            sb.AppendLine("        if not _shape_bucket_matched:");
            sb.AppendLine("            raise KeyError(f\"unknown CUDA/Triton shape bucket ordinal: {_selected_shape_bucket_ordinal}\")");
        }
        else
        {
            foreach (var launch in orderedLaunches)
            {
                sb.AppendLine($"        _launch_{ToPythonKind(launch.Kind)}({Quote(launch.OpName)}, context, [{string.Join(", ", launch.Arguments.Select(Quote))}], separate={ToPythonBool(launch.RequiresCollective)}, launch_meta=_get_launch_metadata(function_meta, {launch.Ordinal.ToString(CultureInfo.InvariantCulture)}))");
            }
        }

        sb.AppendLine("        return context");
        sb.AppendLine("    finally:");
        sb.AppendLine("        _entry_end(function_meta)");
        sb.AppendLine();
    }

    private static void WriteDispatch(StringBuilder sb, IReadOnlyList<CudaTritonFunctionSource> functions)
    {
        sb.AppendLine("def launch(function_id, pe_id, data_pool, output_pool, rdata_pool, *function_args, stream=None, all_data_pools=None, all_output_pools=None, all_rdata_pools=None):");
        if (functions.Count == 0)
        {
            sb.AppendLine("    raise KeyError(f\"unknown cuda triton function id: {function_id}\")");
            return;
        }

        sb.AppendLine("    if all_data_pools is not None and len(all_data_pools) > 1:");
        sb.AppendLine("        if int(pe_id) != 0:");
        sb.AppendLine("            return None");
        sb.AppendLine("        return _execute_multi_pe_function(function_id, *function_args, stream=stream, all_data_pools=all_data_pools, all_output_pools=all_output_pools, all_rdata_pools=all_rdata_pools)");
        foreach (var function in functions)
        {
            sb.AppendLine($"    if function_id == {function.Id.ToString(CultureInfo.InvariantCulture)}:");
            sb.AppendLine($"        return {GetInvokerName(function.Name)}(pe_id, data_pool, output_pool, rdata_pool, *function_args, stream=stream, all_data_pools=all_data_pools, all_output_pools=all_output_pools, all_rdata_pools=all_rdata_pools)");
        }

        sb.AppendLine("    raise KeyError(f\"unknown cuda triton function id: {function_id}\")");
    }

    private static string GetInvokerName(string functionName) => $"invoke_{SanitizeIdentifier(functionName)}";

    private static string SanitizeIdentifier(string value)
    {
        if (string.IsNullOrEmpty(value))
        {
            return "unnamed";
        }

        var sb = new StringBuilder(value.Length);
        for (int i = 0; i < value.Length; i++)
        {
            var ch = value[i];
            sb.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
        }

        if (char.IsDigit(sb[0]))
        {
            sb.Insert(0, '_');
        }

        return sb.ToString();
    }

    private static string ToPythonKind(CudaTritonLaunchKind kind) => kind switch
    {
        CudaTritonLaunchKind.Compute => "compute",
        CudaTritonLaunchKind.Memcopy => "memcopy",
        CudaTritonLaunchKind.Boxing => "boxing",
        CudaTritonLaunchKind.Reduce => "reduce",
        CudaTritonLaunchKind.Matmul => "matmul",
        CudaTritonLaunchKind.Collective => "collective",
        CudaTritonLaunchKind.Function => "function",
        _ => throw new ArgumentOutOfRangeException(nameof(kind), kind, null),
    };

    private static string ToPythonBool(bool value) => value ? "True" : "False";

    private static string JsonBool(bool value) => value ? "true" : "false";

    private static ulong Max(params ulong[] values) => values.Max();

    private static string BuildParameterDescArray(IReadOnlyList<CudaTritonFunctionParameterDesc>? parameters)
    {
        if (parameters == null || parameters.Count == 0)
        {
            return "[]";
        }

        return $"[{string.Join(", ", parameters.Select(BuildParameterDesc))}]";
    }

    private static string BuildParameterDesc(CudaTritonFunctionParameterDesc parameter)
    {
        var parts = new List<string>
        {
            $"{Quote("name")}: {Quote(parameter.Name)}",
        };
        if (parameter.Type != null)
        {
            parts.Add($"{Quote("type")}: {Quote(parameter.Type)}");
        }

        if (parameter.Buffer != null)
        {
            parts.Add($"{Quote("buffer")}: {Quote(parameter.Buffer)}");
        }

        return $"{{{string.Join(", ", parts)}}}";
    }

    private static string BuildReturnDescArray(IReadOnlyList<CudaTritonReturnDesc>? returns)
    {
        if (returns == null || returns.Count == 0)
        {
            return "[]";
        }

        return $"[{string.Join(", ", returns.Select(BuildReturnDesc))}]";
    }

    private static string BuildReturnDesc(CudaTritonReturnDesc ret)
    {
        return $"{{{Quote("index")}: {ret.Index.ToString(CultureInfo.InvariantCulture)}, {Quote("value")}: {Quote(ret.Value)}, {Quote("buffer")}: {BuildBufferDesc(ret.Buffer)}}}";
    }

    private static string BuildBufferMap(IReadOnlyDictionary<string, CudaTritonBufferDesc>? buffers)
    {
        if (buffers == null || buffers.Count == 0)
        {
            return "{}";
        }

        return $"{{{string.Join(", ", buffers.OrderBy(kv => kv.Key, StringComparer.Ordinal).Select(kv => $"{Quote(kv.Key)}: {BuildBufferDesc(kv.Value)}"))}}}";
    }

    private static string BuildBufferDesc(CudaTritonBufferDesc buffer)
    {
        var parts = new List<string>
        {
            $"{Quote("name")}: {Quote(buffer.Name)}",
            $"{Quote("dtype")}: {Quote(buffer.DType)}",
            $"{Quote("element_size_bytes")}: {buffer.ElementSizeBytes.ToString(CultureInfo.InvariantCulture)}",
            $"{Quote("rank")}: {buffer.Rank.ToString(CultureInfo.InvariantCulture)}",
            $"{Quote("shape")}: [{string.Join(", ", buffer.Shape.Select(BuildDimDesc))}]",
            $"{Quote("strides")}: [{string.Join(", ", buffer.Strides.Select(BuildStrideDesc))}]",
            $"{Quote("memory")}: {BuildMemoryDesc(buffer.Memory)}",
        };

        if (buffer.DistributedType != null)
        {
            parts.Add($"{Quote("distributed_type")}: {Quote(buffer.DistributedType)}");
        }

        return $"{{{string.Join(", ", parts)}}}";
    }

    private static string BuildMemoryDesc(CudaTritonMemoryDesc memory)
    {
        var parts = new List<string>
        {
            $"{Quote("location")}: {Quote(memory.Location)}",
            $"{Quote("hierarchy")}: {memory.Hierarchy.ToString(CultureInfo.InvariantCulture)}",
            $"{Quote("alignment")}: {memory.Alignment.ToString(CultureInfo.InvariantCulture)}",
            $"{Quote("buffer_size_bytes")}: {BuildDimDesc(memory.BufferSizeBytes)}",
            $"{Quote("span_start_bytes")}: {BuildDimDesc(memory.SpanStartBytes)}",
            $"{Quote("span_size_bytes")}: {BuildDimDesc(memory.SpanSizeBytes)}",
            $"{Quote("base_start")}: {BuildNullableString(memory.BaseStart)}",
        };
        return $"{{{string.Join(", ", parts)}}}";
    }

    private static string BuildDimDesc(CudaTritonDimDesc dim)
    {
        var parts = new List<string>
        {
            $"{Quote("kind")}: {Quote(dim.Kind)}",
        };
        if (dim.Value.HasValue)
        {
            parts.Add($"{Quote("value")}: {dim.Value.Value.ToString(CultureInfo.InvariantCulture)}");
        }

        if (dim.Symbol != null)
        {
            parts.Add($"{Quote("symbol")}: {Quote(dim.Symbol)}");
        }

        if (dim.Expression != null)
        {
            parts.Add($"{Quote("expression")}: {Quote(dim.Expression)}");
        }

        return $"{{{string.Join(", ", parts)}}}";
    }

    private static string BuildStrideDesc(CudaTritonStrideDesc stride)
        => BuildDimDesc(new CudaTritonDimDesc(stride.Kind, stride.Value, stride.Symbol, stride.Expression));

    private static string BuildAttributeMap(IReadOnlyDictionary<string, object?>? attributes)
    {
        if (attributes == null || attributes.Count == 0)
        {
            return "{}";
        }

        return $"{{{string.Join(", ", attributes.OrderBy(kv => kv.Key, StringComparer.Ordinal).Select(kv => $"{Quote(kv.Key)}: {BuildJsonValue(kv.Value)}"))}}}";
    }

    private static string BuildJsonValue(object? value) => value switch
    {
        null => "null",
        string s => Quote(s),
        bool b => JsonBool(b),
        byte b => b.ToString(CultureInfo.InvariantCulture),
        sbyte b => b.ToString(CultureInfo.InvariantCulture),
        short s => s.ToString(CultureInfo.InvariantCulture),
        ushort s => s.ToString(CultureInfo.InvariantCulture),
        int i => i.ToString(CultureInfo.InvariantCulture),
        uint i => i.ToString(CultureInfo.InvariantCulture),
        long l => l.ToString(CultureInfo.InvariantCulture),
        ulong l => l.ToString(CultureInfo.InvariantCulture),
        float f => float.IsFinite(f) ? f.ToString("R", CultureInfo.InvariantCulture) : Quote(f.ToString(CultureInfo.InvariantCulture)),
        double d => double.IsFinite(d) ? d.ToString("R", CultureInfo.InvariantCulture) : Quote(d.ToString(CultureInfo.InvariantCulture)),
        decimal d => d.ToString(CultureInfo.InvariantCulture),
        CudaTritonDimDesc dim => BuildDimDesc(dim),
        CudaTritonStrideDesc stride => BuildStrideDesc(stride),
        CudaTritonMemoryDesc memory => BuildMemoryDesc(memory),
        CudaTritonBufferDesc buffer => BuildBufferDesc(buffer),
        IReadOnlyDictionary<string, object?> map => BuildAttributeMap(map),
        IEnumerable enumerable => $"[{string.Join(", ", enumerable.Cast<object?>().Select(BuildJsonValue))}]",
        _ => Quote(value.ToString() ?? string.Empty),
    };

    private static string BuildNullableString(string? value) => value == null ? "null" : Quote(value);

    private static string Quote(string value)
    {
        var escaped = value
            .Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal)
            .Replace("\r", "\\r", StringComparison.Ordinal)
            .Replace("\n", "\\n", StringComparison.Ordinal);
        return $"\"{escaped}\"";
    }
